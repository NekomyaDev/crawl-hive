const TG: Record<Lang, TgDict> = { en, es, pt, ru, tr, zh };

// Текст бота на языке чата с подстановкой {имя}; пропущенный ключ падает на английский.
export function tt(lang: Lang, key: TgKey, vars?: Record<string, string | number>) {
  return fill(TG[lang]?.[key] ?? en[key], vars);
}

// Меню команд (setMyCommands) в порядке показа; описания по языкам.
